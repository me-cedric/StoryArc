//! Writes the C# side of the seam from the Rust side (task 1.8a of `desktop-clients`).
//!
//! `generated/NativeMethods.g.cs` is produced here by csbindgen from the `extern "C"`
//! functions of `src/lib.rs`, committed, and linked into `StoryArc.Interop` by lane W. The
//! file is regenerated on every build of this crate, so a changed export shows up as a diff
//! in review rather than as a `DllImport` that silently disagrees with the library.
//!
//! The generator writes into `OUT_DIR` first and touches the source tree only when the
//! committed file differs. `container-build.sh` mounts the repository read-only, and a
//! build that wrote unconditionally panicked there with "Read-only file system" on every
//! distro; a build that cannot write a *changed* file fails naming the drift instead, so
//! the fix is one `cargo build` on a writable checkout and a commit.

use std::env;
use std::path::PathBuf;

const HEADER: &str = "// Generated by apps/desktop-core/storyarc-ffi/build.rs with csbindgen 1.9.8. Do not edit.\n// The Rust side is apps/desktop-core/storyarc-ffi/src/lib.rs; the C header is include/storyarc_ffi.h.";

fn main() {
    let crate_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    let input = crate_dir.join("src/lib.rs");
    let committed = crate_dir.join("generated/NativeMethods.g.cs");
    let fresh = out_dir.join("NativeMethods.g.cs");
    println!("cargo::rerun-if-changed={}", input.display());
    println!("cargo::rerun-if-changed={}", committed.display());

    csbindgen::Builder::default()
        .input_extern_file(&input)
        .csharp_dll_name("storyarc_ffi")
        .csharp_namespace("StoryArc.Interop")
        .csharp_class_name("NativeMethods")
        .csharp_class_accessibility("internal")
        .csharp_file_header(HEADER)
        .generate_csharp_file(&fresh)
        .expect("write the generated C# declarations into OUT_DIR");

    let generated = std::fs::read(&fresh).expect("read the generated C# declarations back");
    if std::fs::read(&committed).is_ok_and(|current| current == generated) {
        return;
    }
    if std::fs::write(&committed, &generated).is_err() {
        panic!(
            "generated/NativeMethods.g.cs is out of date, run cargo build on a writable checkout and commit it"
        );
    }
}
